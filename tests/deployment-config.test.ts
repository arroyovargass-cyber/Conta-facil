import { it, expect } from "vitest";
import { parseConfig } from "../apps/api/src/config";
import { databaseOptions } from "../apps/api/src/database-options";
const env = {
  NODE_ENV: "production",
  APP_ORIGIN: "https://conta-facil-pruebas.onrender.com",
  SUPABASE_URL: "https://example.supabase.co",
  SUPABASE_ANON_KEY: "public-example-key",
  SUPABASE_SERVICE_KEY: "private-example-key",
  SESSION_KEY: "a".repeat(64),
  DATABASE_URL:
    "postgresql://conta_facil_api.ref:example@aws-0-us-east-1.pooler.supabase.com:5432/postgres",
};
it("requires real HTTPS and remote database settings for deployment", () => {
  expect(() =>
    parseConfig({ ...env, APP_ORIGIN: "http://localhost:5173" }),
  ).toThrow();
  expect(() =>
    parseConfig({ ...env, SUPABASE_URL: "http://127.0.0.1:54321" }),
  ).toThrow();
  expect(() => parseConfig({ ...env, DATABASE_URL: undefined })).toThrow();
});
it("uses the actual Render URL and serves the built site", () => {
  const c = parseConfig({
    ...env,
    APP_ORIGIN: undefined,
    RENDER_EXTERNAL_URL: env.APP_ORIGIN,
  });
  expect(c.APP_ORIGIN).toBe(env.APP_ORIGIN);
  expect(c.STATIC_DIRECTORY).toBeDefined();
});
it("requires certificate verification even when URL attempts to weaken SSL", () => {
  const c = parseConfig({
      ...env,
      DATABASE_URL: env.DATABASE_URL + "?sslmode=no-verify",
    }),
    options = databaseOptions(c);
  expect(options.ssl).toMatchObject({ rejectUnauthorized: true });
  expect(options.connectionString).not.toContain("sslmode");
  expect(options.max).toBeLessThanOrEqual(5);
});
it("keeps loopback development compatible without SSL", () => {
  const c = parseConfig({
    ...env,
    NODE_ENV: "development",
    DATABASE_URL: "postgresql://postgres:postgres@127.0.0.1:54322/postgres",
    APP_ORIGIN: "http://localhost:5173",
    SUPABASE_URL: "http://127.0.0.1:54321",
  });
  expect(databaseOptions(c).ssl).toBe(false);
});
it("accepts the 256-bit base64 secret generated by Render", () => {
  const raw = Buffer.alloc(32, 127).toString("base64");
  expect(parseConfig({ ...env, SESSION_KEY: raw }).SESSION_KEY).toBe(
    Buffer.alloc(32, 127).toString("hex"),
  );
});
it("reports all missing deployment variables together without exposing configured secrets", () => {
  const suppliedSecret = "synthetic-secret-must-not-appear";
  let failure: unknown;
  try {
    parseConfig({
      NODE_ENV: "production",
      SUPABASE_ANON_KEY: suppliedSecret,
      SUPABASE_SERVICE_KEY: "   ",
    });
  } catch (error) {
    failure = error;
  }
  expect(failure).toBeInstanceOf(Error);
  expect((failure as Error).message).toBe(
    "Faltan variables de configuración: DATABASE_URL, SUPABASE_URL, SUPABASE_SERVICE_KEY, SESSION_KEY, APP_ORIGIN (o RENDER_EXTERNAL_URL). Configúralas en Environment Variables y guarda el despliegue.",
  );
  expect(String(failure)).not.toContain(suppliedSecret);
});
it("keeps fiscal environments independently disabled and preserves the prior response trust default", () => {
  const c = parseConfig(env);
  expect(c.HACIENDA_STAG_PROBE_ENABLED).toBe("false");
  expect(c.HACIENDA_PRODUCTION_PROBE_ENABLED).toBe("false");
  expect(c.HACIENDA_STAG_EMISSION_ENABLED).toBe("false");
  expect(c.HACIENDA_PRODUCTION_EMISSION_ENABLED).toBe("false");
  expect(c.HACIENDA_RESPONSE_TRUST_POLICY).toBe("pinned_certificate");
});
it("accepts an explicit official API response policy without enabling any fiscal environment", () => {
  const c = parseConfig({
    ...env,
    HACIENDA_RESPONSE_TRUST_POLICY: "official_api",
  });
  expect(c.HACIENDA_RESPONSE_TRUST_POLICY).toBe("official_api");
  expect(c.HACIENDA_PRODUCTION_EMISSION_ENABLED).toBe("false");
  expect(() =>
    parseConfig({ ...env, HACIENDA_RESPONSE_TRUST_POLICY: "trust_any_xml" }),
  ).toThrow();
});
